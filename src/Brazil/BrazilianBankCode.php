    /**
     * @return string[]
     */
    public function labelList(): array
    {
        return array_map(fn (self $case) => $case->label(), self::cases());
    }

    /**
     * @return array<string, string>
     */
    public static function toArray(): array
    {
        $result = [];

        foreach (self::cases() as $bank) {
            $result[$bank->value] = $bank->value;
        }

        return $result;
    }

    /**
     * @return array<string, string>
     */
    public static function toArrayWithLabels(): array
    {
        $result = [];

        foreach (self::cases() as $bank) {
            $result[$bank->value] = $bank->label();
        }

        return $result;
    }

    /**
     * @return array<string, string>
     */
    public static function toArrayWithShortNames(): array
    {
        $result = [];

        foreach (self::cases() as $bank) {
            $result[$bank->value] = $bank->shortName();
        }

        return $result;
    }
